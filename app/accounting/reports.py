# --------------------------------------------------------------------------- HTML rendering
def _inline(text: str) -> str:
    t = html.escape(text)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w])_(.+?)_(?![\w])", r"<em>\1</em>", t)
    return t


def markdown_to_html(md: str, title: str) -> str:
    """Render the (simple, self-generated) report markdown as standalone printable HTML. Escapes all text."""
    body: list[str] = []
    lines = md.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[-|]+\|?$", lines[i + 1]):
            head = [c.strip() for c in ln.strip("|").split("|")]
            body.append("<table><thead><tr>" + "".join(f"<th>{_inline(h)}</th>" for h in head) + "</tr></thead><tbody>")
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip("|").split("|")]
                body.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells) + "</tr>")
                i += 1
            body.append("</tbody></table>")
            continue
        if ln.startswith("### "):
            body.append(f"<h3>{_inline(ln[4:])}</h3>")
        elif ln.startswith("## "):
            body.append(f"<h2>{_inline(ln[3:])}</h2>")
        elif ln.startswith("# "):
            body.append(f"<h1>{_inline(ln[2:])}</h1>")
        elif ln.startswith("- "):
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(f"<li>{_inline(lines[i][2:])}</li>")
                i += 1
            body.append("<ul>" + "".join(items) + "</ul>")
            continue
        elif ln.startswith("> "):
            body.append(f"<blockquote>{_inline(ln[2:])}</blockquote>")
        elif ln.strip():
            body.append(f"<p>{_inline(ln)}</p>")
        i += 1
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{html.escape(title)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
body{{font:14px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Arial,sans-serif;color:#1b1f24;max-width:960px;margin:32px auto;padding:0 16px}}
h1{{font-size:22px}} h2{{font-size:17px;margin-top:28px;border-bottom:1px solid #dfe3e8;padding-bottom:4px}} h3{{font-size:14px}}
table{{border-collapse:collapse;width:100%;margin:8px 0 16px;font-size:13px}} th,td{{border:1px solid #dfe3e8;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#f0f2f5}} blockquote{{margin:6px 0;padding:6px 12px;border-left:3px solid #2457d6;background:#f6f7f9}}
em{{color:#5f6b7a}} .ai{{background:#fff4dc;border-radius:8px;padding:10px 14px}}
@media print{{body{{margin:0}} h2{{break-after:avoid}} table{{break-inside:auto}} tr{{break-inside:avoid}}}}
</style></head><body>{''.join(body)}</body></html>"""
